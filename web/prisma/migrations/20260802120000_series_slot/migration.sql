-- Позиция серии в сетке плей-офф: ключ слота из src/lib/playoff-bracket.ts («ub-qf1», «gf»).
-- По нему страница плей-офф раскладывает серии по местам сетки и вычисляет участников поздних
-- слотов из исходов ранних. У групповых серий пусто.

ALTER TABLE "Series" ADD COLUMN "slot" TEXT;

-- Один слот сетки — одна серия. slot=NULL (групповые) в sqlite-уникальности различны между собой,
-- поэтому этот индекс ограничивает только плей-офф.
CREATE UNIQUE INDEX "Series_division_slot_key" ON "Series"("division", "slot");
