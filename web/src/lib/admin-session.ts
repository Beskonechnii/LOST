// Только сервер: «а есть ли у вошедшего права администратора?» для серверных компонентов.
//
// Нужна там, где страница публичная, но часть содержимого — нет: витрины ростера показывают всем
// состав команд, а формы «добавить» и операторскую диагностику — только админам. Роль берём из
// сессии (owner/admin), без похода в БД — этого достаточно, чтобы решить, показывать ли
// операторский кусок. Сама запись всё равно закрыта в needsAdmin() на уровне API.

import { currentSession } from "./player-session";

export async function isAdmin(): Promise<boolean> {
  // Через currentSession, а не напрямую по куке: иначе локальный dev-автовход (DEV_LOGIN_EMAIL)
  // виден кабинету, но не навигации — вкладка «Админ» и операторские куски пропадали у владельца,
  // который «вошёл» без куки.
  const session = await currentSession();
  return session?.role === "owner" || session?.role === "admin";
}
